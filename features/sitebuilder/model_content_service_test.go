func TestPrepareModelContentDraftRecordsKeepsRecordEntityIdentity(t *testing.T) {
	recordID := uuid.NewString()
	known := knownModelRecordEntities(
		[]ModelContentRecord{{ID: recordID, EntityID: "products"}},
		[]ModelContentRecord{{ID: recordID, EntityID: "products"}},
	)
	updated, err := prepareModelContentDraftRecords([]ModelContentRecord{{ID: recordID, EntityID: "products"}}, known)
	if err != nil {
		t.Fatalf("prepare existing record: %v", err)
	}
	if updated[0].ID != recordID || updated[0].EntityID != "products" {
		t.Fatalf("existing record identity changed: %#v", updated[0])
	}

	if _, err := prepareModelContentDraftRecords([]ModelContentRecord{{ID: recordID, EntityID: "categories"}}, known); err == nil {
		t.Fatal("changing the entity of an existing record was accepted")
	}
	if _, err := prepareModelContentDraftRecords([]ModelContentRecord{{ID: uuid.NewString(), EntityID: "products"}}, known); err == nil {
		t.Fatal("client supplied ID for a new record was accepted")
	}

	created, err := prepareModelContentDraftRecords([]ModelContentRecord{{EntityID: "products"}}, known)
	if err != nil {
		t.Fatalf("prepare new record: %v", err)
	}
	if _, err := uuid.Parse(created[0].ID); err != nil || created[0].ID == "" {
		t.Fatalf("new record ID was not generated by the server: %q", created[0].ID)
	}
}

func TestSingletonDraftPreparationSeedsEmptyRowsAndPreservesExistingIdentity(t *testing.T) {
	const singletonID = "00000000-0000-4000-8000-000000000021"
	const manyID = "00000000-0000-4000-8000-000000000022"
	model := DataModel{FormatVersion: 1, Entities: []DataModelEntity{
		{ID: singletonID, Key: "site_settings", Name: "Site settings", Cardinality: DataModelEntityCardinalitySingleton},
		{ID: manyID, Key: "products", Name: "Products"},
	}}
	existingID := uuid.NewString()
	existing := ModelContentRecord{ID: existingID, EntityID: manyID, SortOrder: 2, Values: map[string]any{"title": "Keep me"}, Relations: map[string][]string{}}
	seeded, changed, err := seedSingletonDraftRecords(model, []ModelContentRecord{existing})
	if err != nil {
		t.Fatalf("seed missing singleton: %v", err)
	}
	if !changed || len(seeded) != 2 || seeded[0].ID != existingID || seeded[0].Values["title"] != "Keep me" || seeded[0].SortOrder != 2 {
		t.Fatalf("seeding must preserve existing rows and add exactly one singleton: changed=%v rows=%+v", changed, seeded)
	}
	newRow := seeded[1]
	if newRow.EntityID != singletonID || len(newRow.Values) != 0 || len(newRow.Relations) != 0 || newRow.SortOrder != 0 {
		t.Fatalf("generated singleton row should be empty: %+v", newRow)
	}
	if _, err := uuid.Parse(newRow.ID); err != nil || newRow.ID == "" {
		t.Fatalf("singleton row ID should be generated UUID: %q (%v)", newRow.ID, err)
	}
	seededAgain, changed, err := seedSingletonDraftRecords(model, seeded)
	if err != nil || changed || len(seededAgain) != len(seeded) || seededAgain[1].ID != newRow.ID {
		t.Fatalf("re-seeding must be idempotent: changed=%v rows=%+v err=%v", changed, seededAgain, err)
	}
	firstSingleton := existing
	firstSingleton.EntityID = singletonID
	if _, _, err := seedSingletonDraftRecords(model, []ModelContentRecord{firstSingleton, {ID: uuid.NewString(), EntityID: singletonID}}); err == nil {
		t.Fatal("seeding must fail closed instead of deleting duplicate singleton rows")
	}
}

func TestSingletonDraftPreparationPreservesRecordIDWhenClearingValues(t *testing.T) {
	entityID := uuid.NewString()
	model := DataModel{FormatVersion: 1, Entities: []DataModelEntity{{
		ID: entityID, Key: "site_settings", Name: "Site settings", Cardinality: DataModelEntityCardinalitySingleton,
	}}}
	currentID := uuid.NewString()
	current := []ModelContentRecord{{ID: currentID, EntityID: entityID, Values: map[string]any{"title": "Old"}}}
	input, err := preserveSingletonDraftRecordIDs(model, []ModelContentRecord{{EntityID: entityID, Values: map[string]any{}}}, current)
	if err != nil {
		t.Fatalf("preserve ID while clearing values: %v", err)
	}
	known := knownModelRecordEntities(current)
	prepared, err := prepareModelContentDraftRecords(input, known)
	if err != nil {
		t.Fatalf("prepare cleared singleton: %v", err)
	}
	if prepared[0].ID != currentID || len(prepared[0].Values) != 0 {
		t.Fatalf("clearing values must keep the singleton identity: %+v", prepared[0])
	}
	if _, err := preserveSingletonDraftRecordIDs(model, []ModelContentRecord{{ID: uuid.NewString(), EntityID: entityID}}, current); err == nil {
		t.Fatal("replacing an existing singleton ID must be rejected")
	}
}

func TestModelContentPlacementSummariesExposeMappedMediaPreparation(t *testing.T) {
	profile := validDataInputMediaProfile()
	manifest, err := json.Marshal(Manifest{
		FormatVersion: 2,
		DataInputs:    []DataInputPort{{Key: "products", Kind: "collection", Fields: []DataInputField{{Path: "/imageSrc", Type: "media", Profile: profile}}}},
	})
	if err != nil {
		t.Fatal(err)
	}
	modelFieldID := uuid.NewString()
	payload := SnapshotPayload{
		Builds: []PinnedBuild{{Key: "catalog", Name: "Catalog", Version: "2.0.0", Digest: "build-digest", Manifest: manifest}},
		Config: SiteConfig{Pages: []Page{{ID: "catalog-page", Name: "Catalog", Placements: []Placement{{
			ID: "catalog-placement", Build: BuildRef{FeatureKey: "catalog", Version: "2.0.0"},
			DataBindings: []DataInputBinding{{InputKey: "products", EntityID: uuid.NewString(), Fields: []DataInputFieldBinding{{InputPath: "/imageSrc", FieldID: modelFieldID}}}},
		}}}}},
	}
	summaries, err := modelContentPlacementSummaries(payload)
	if err != nil {
		t.Fatal(err)
	}
	if len(summaries) != 1 || len(summaries[0].Inputs) != 1 || len(summaries[0].Inputs[0].Fields) != 1 {
		t.Fatalf("unexpected placement summaries: %+v", summaries)
	}
	field := summaries[0].Inputs[0].Fields[0]
	if field.FieldID != modelFieldID || len(field.Preparations) != 1 {
		t.Fatalf("media preparation was not attached to the mapped model field: %+v", field)
	}
	preparation := field.Preparations[0]
	if preparation.FeatureKey != "catalog" || preparation.BuildVersion != "2.0.0" || preparation.SchemaKind != "dataInputs" || preparation.FieldPath != "/products/imageSrc" || preparation.BuildDigest != "build-digest" || preparation.Accept != "raster-image" {
		t.Fatalf("incorrect media preparation context: %+v", preparation)
	}
}

func TestNonNilModelSelectionsEncodesAbsentAndEmptySelectionsAsArray(t *testing.T) {
	for name, input := range map[string][]ModelContentSelection{
		"absent": nil,
		"empty":  {},
	} {
		t.Run(name, func(t *testing.T) {
			raw, err := json.Marshal(nonNilModelSelections(input))
			if err != nil {
				t.Fatal(err)
			}
			if string(raw) != "[]" {
				t.Fatalf("empty selections encoded as %s, want []", raw)
			}
		})
	}
}

func TestRewriteModelRecordMediaOnlyTouchesDeclaredMediaFields(t *testing.T) {
	fileID := uuid.NewString()
	model := DataModel{Entities: []DataModelEntity{{
		ID: "products",
		Fields: []DataModelField{
			{ID: "image", Key: "image", Type: "media"},
			{ID: "slug", Key: "slug", Type: "text"},
		},
	}}}
	records := []ModelContentRecord{{ID: uuid.NewString(), EntityID: "products", Values: map[string]any{"image": fileID, "slug": fileID}}}
	refs := newPackReferences(nil)
	refs.clearTarget = fileID
	rewritten, changed, err := rewriteModelRecordMedia(model, records, refs)
	if err != nil {
		t.Fatalf("rewrite model media: %v", err)
	}
	if !changed || !refs.cleared {
		t.Fatal("declared media reference was not reported")
	}
	if rewritten[0].Values["image"] != "" {
		t.Fatalf("media reference was not cleared: %#v", rewritten[0].Values["image"])
	}
	if rewritten[0].Values["slug"] != fileID {
		t.Fatalf("untyped matching value was changed: %#v", rewritten[0].Values["slug"])
	}
}
